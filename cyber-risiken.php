                <h2>Ursachen</h2>
                <ul>
                    <li><strong>Externe Angriffe:</strong> Ransomware, Phishing, Business Email Compromise (BEC), Exploits, DDoS, Datendiebstahl, Supply-Chain</li>
                    <li><strong>Interne Fehler:</strong> Fehlbedienung, versehentliches Löschen, falsche Rollen- und Rechtevergabe</li>
                    <li><strong>Fehlkonfigurationen:</strong> Cloud-Storage öffentlich, zu breite Admin-Rechte, fehlende MFA, falsche Netzwerkregeln</li>
                    <li><strong>Change- und Release-Risiken:</strong> ungetestete Updates, unsaubere Deployments, fehlende Rollback-Strategien</li>
                    <li><strong>Technische Störungen:</strong> Identitätsdienst- und DNS-Ausfälle, Zertifikatsablauf, Backup-Fehler, Kapazitätsengpässe</li>
                    <li><strong>Drittparteien &amp; Lieferkette:</strong> Dienstleisterausfall, Kompromittierung eines Dienstleisters mit Auswirkungen auf das eigene System, kompromittierte Software, unklare Verantwortlichkeiten in Outsourcing und SaaS</li>
                </ul>
            </div>
            <!-- Auswirkungen -->
            <div class="rdcol bg bgblue">
                <h2>Auswirkungen</h2>
                <ul>
                    <li><strong>Betriebsunterbruch:</strong> Produktionsstillstand, Ausfall Kundenportale und ERP, Störung kritischer Services (auch OT)</li>
                    <li><strong>Finanzen:</strong> Umsatzverlust, Zusatzkosten (Forensik, Wiederherstellung, Überstunden), Vertragsstrafen, Erpressung</li>
                    <li><strong>Daten &amp; IP:</strong> Verlust und Manipulation sensibler Daten, Know-how-Abfluss, Integritätsprobleme (falsche Stammdaten)</li>
                    <li><strong>Recht &amp; Compliance:</strong> Datenschutzmeldungen, Audits, mögliche Sanktionen, Haftung gegenüber Kunden und Partnern</li>
                    <li><strong>Reputation:</strong> Vertrauensverlust, negative Medien, erschwerte Neukundengewinnung, höhere Vendor-Due-Diligence-Hürden</li>
                    <li><strong>Management-Belastung:</strong> Krisenstab, Entscheidungsdruck, Priorisierung von Wiederanlauf vs. Informationspflichten</li>
                    <li><strong>Strategische Folgewirkungen:</strong> Verzögerung von Transformationsprogrammen, Umpriorisierung von Investitionen, steigende Versicherungsprämien</li>
                </ul>
            </div>
            <!-- Bewältigungsmassnahmen -->
            <div class="rdcol bg bggreen">
                <h2>Bewältigungsmassnahmen</h2>
                <ul>
                    <li><strong>Governance &amp; Verantwortung:</strong> klare Rollen (CISO, IT, Business), Risikobesitz, Entscheidungswege, GL-Reporting (KRI/KPI)</li>
                    <li><strong>Härtung &amp; Standardisierung:</strong> Baselines, Zero-Trust-Prinzipien, MFA, Least-Privilege, sichere Konfigurationsstandards</li>
                    <li><strong>Change- und Config-Kontrollen:</strong> Change-Management, Vier-Augen-Prinzip, IaC-Policy-Checks, automatisierte Konfigurationsprüfungen</li>
                    <li><strong>Detektion &amp; Reaktion:</strong> Logging und Monitoring, SOC/EDR/MDR, Alarmierungsprozesse, Playbooks, regelmässige Table-Top-Exercises</li>
                    <li><strong>Wiederherstellbarkeit:</strong> getestete Backups (immutable/offline), definierte RTO/RPO, Notbetriebskonzepte, Wiederanlaufübungen</li>
                    <li><strong>Drittparteien &amp; Lieferkette:</strong> Sicherheitsanforderungen, Vertragsklauseln, Exit-Pläne, Risikoklassierung von Providern</li>
                    <li><strong>Awareness &amp; Fehlerkultur:</strong> Schulungen (Phishing, Datenhandling), simulierte Phishing-Attacken, sichere Prozesse, Meldekultur für Near-Misses</li>
                    <li><strong>Versicherung &amp; Risikotransfer:</strong> Abgleich Restrisiko vs. Deckung, klare Incident-Kostenmodelle, Nachweisfähigkeit (Controls)</li>
                </ul>
