                <h2>Auswirkungen</h2>
                <ul>
                    <li><strong>Fehlentscheidungen:</strong> falsche Empfehlungen, fehlerhafte Automatisierung, Qualitätsmängel</li>
                    <li><strong>Recht &amp; Compliance:</strong> Datenschutzverstösse, IP- und Urheberrechtsrisiken, Diskriminierungs- oder Transparenzpflichten</li>
                    <li><strong>Reputation:</strong> Vertrauensverlust durch falsche oder irreführende KI-Outputs, ethische Kritik</li>
                    <li><strong>Security &amp; Fraud:</strong> Deepfakes, Identitätsmissbrauch, Social Engineering</li>
                    <li><strong>Abhängigkeiten:</strong> Vendor Lock-in, Preis- und Verfügbarkeitsrisiken, unklare Haftungsketten</li>
                    <li><strong>Betrieb:</strong> Kostenvolatilität (Token/Compute), Leistungs- und Latenzprobleme, Monitoring- und Governance-Aufwände</li>
                </ul>
