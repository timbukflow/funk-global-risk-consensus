                <ul>
                    <li><strong>KI-Governance:</strong> Policy, Risikoklassierung (kritische vs. nichtkritische Use Cases), Verantwortlichkeiten, GL-Oversight</li>
                    <li><strong>Sichere Plattform:</strong> freigegebene Tools und Modelle, Datenraumkonzepte, Zugriffskontrollen, Protokollierung</li>
                    <li><strong>Qualitätskontrollen:</strong> Validierung, Red-Teaming, Bias-Tests, fachliche Freigabe, Human-in-the-Loop bei kritischen Entscheidungen</li>
                    <li><strong>Datenschutz &amp; IP:</strong> klare Regeln zu Dateninput, Vertragsklauseln mit Anbietern, Datenminimierung und Anonymisierung</li>
                    <li><strong>Security by Design:</strong> sichere Integrationen, Prompt-Injection-Schutz, Secret-Handling, Monitoring von Missbrauch</li>
                    <li><strong>Befähigung:</strong> Schulungen für Mitarbeitende und Management, definierte Do's &amp; Don'ts, Meldewege für Vorfälle</li>
                    <li><strong>Kontinuierliches Monitoring:</strong> Modell-Drift, Output-Qualität, Kosten, regulatorische Entwicklungen</li>
