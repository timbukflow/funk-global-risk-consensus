                <h2>Ursachen</h2>
                <ul>
                    <li><strong>Mangelnde Governance:</strong> Unkontrollierte Tool-Nutzung (Shadow AI), fehlende Richtlinien und Freigabeprozesse</li>
                    <li><strong>Datenmanagement:</strong> Unklare Datenherkunft und -qualität, sensibler Datenabfluss, unzureichende Anonymisierung</li>
                    <li><strong>Modellrisiken:</strong> Halluzinationen, Bias, mangelnde Erklärbarkeit, fehlende Robustheit</li>
                    <li><strong>Sicherheitsrisiken:</strong> Prompt-Injection, Datenexfiltration, unsichere Integrationen und APIs</li>
                    <li><strong>Markt- und Complianceanforderungen:</strong> Dynamische Regulierung und steigende Kunden- und Partneranforderungen</li>
